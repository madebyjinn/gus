import AppKit

/// Remembers what you copy: text, links, file paths and images. Watches the pasteboard's change
/// count twice a second (a single integer read), so it costs nothing at rest. Skips anything a password
/// manager marks concealed or transient. Kept on this Mac only, in Application Support/Gus.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    struct Clip: Codable, Identifiable, Equatable {
        enum Kind: String, Codable { case text, link, file, image }
        var id = UUID()
        var kind: Kind
        var text: String           // the text, the URL, the path, or "Image 1200 × 800"
        var imageFile: String?     // PNG name inside the history folder
        var app: String?           // where it was copied
        var date = Date()
    }

    @Published private(set) var clips: [Clip] = []
    var enabled: Bool { UserDefaults.standard.object(forKey: "clipboardHistory") as? Bool ?? true }
    static let limit = 200

    private var lastCount = NSPasteboard.general.changeCount
    private var skipCount: Int?
    private var timer: Timer?

    private let folder: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Gus/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()
    private var index: URL { folder.appendingPathComponent("history.json") }

    private init() {
        if let data = try? Data(contentsOf: index), let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = saved
        }
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.25
    }

    /// Our own copies (choosing a clip, copying a result) shouldn't come back as new entries.
    func ignoreNextChange() { skipCount = NSPasteboard.general.changeCount }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if skipCount == pb.changeCount { skipCount = nil; return }
        guard enabled else { return }
        let types = pb.types ?? []
        let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                   "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                   "com.typeit4me.clipping", "Pasteboard generator type"]
        if types.contains(where: { secret.contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], let file = urls.first {
            add(Clip(kind: .file, text: file.path, app: app))
        } else if let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = String(string.prefix(20_000))
            let isLink = URL(string: trimmed.trimmingCharacters(in: .whitespaces)).map { $0.scheme?.hasPrefix("http") == true } ?? false
            add(Clip(kind: isLink ? .link : .text, text: trimmed, app: app))
        } else if let image = NSImage(pasteboard: pb), let png = Self.png(image, maxSide: 1600) {
            let name = UUID().uuidString + ".png"
            try? png.write(to: folder.appendingPathComponent(name))
            let size = image.size
            add(Clip(kind: .image, text: "Image \(Int(size.width)) × \(Int(size.height))", imageFile: name, app: app))
        }
    }

    private func add(_ clip: Clip) {
        // Copying the same thing again moves it to the top instead of duplicating it.
        if let old = clips.firstIndex(where: { $0.kind == clip.kind && $0.text == clip.text && clip.kind != .image }) {
            clips.remove(at: old)
        }
        clips.insert(clip, at: 0)
        while clips.count > Self.limit { remove(clips.removeLast()) }
        save()
        NotificationCenter.default.post(name: .gusCopied, object: nil)
    }

    func use(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.kind {
        case .text, .link: pb.setString(clip.text, forType: .string)
        case .file: pb.writeObjects([URL(fileURLWithPath: clip.text) as NSURL])
        case .image:
            if let name = clip.imageFile, let image = NSImage(contentsOf: folder.appendingPathComponent(name)) {
                pb.writeObjects([image])
            }
        }
        ignoreNextChange()
        // Used again: it goes back to the top.
        if let i = clips.firstIndex(of: clip) { var c = clips.remove(at: i); c.date = Date(); clips.insert(c, at: 0); save() }
    }

    func delete(_ clip: Clip) {
        clips.removeAll { $0.id == clip.id }
        remove(clip)
        save()
    }

    func clear() {
        clips.forEach(remove)
        clips.removeAll()
        save()
    }

    func image(for clip: Clip) -> NSImage? {
        clip.imageFile.flatMap { NSImage(contentsOf: folder.appendingPathComponent($0)) }
    }

    private func remove(_ clip: Clip) {
        if let name = clip.imageFile { try? FileManager.default.removeItem(at: folder.appendingPathComponent(name)) }
    }

    private func save() {
        let snapshot = clips
        let url = index
        DispatchQueue.global(qos: .utility).async {
            if let data = try? JSONEncoder().encode(snapshot) { try? data.write(to: url, options: .atomic) }
        }
    }

    private static func png(_ image: NSImage, maxSide: CGFloat) -> Data? {
        let scale = min(1, maxSide / max(image.size.width, image.size.height, 1))
        let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
        guard size.width >= 1, size.height >= 1 else { return nil }
        let out = NSImage(size: size)
        out.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: size))
        out.unlockFocus()
        guard let tiff = out.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
}
