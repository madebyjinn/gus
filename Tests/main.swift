import Foundation
var fails = 0
func check(_ ok: Bool, _ what: String) { if !ok { fails += 1; print("FAIL", what) } }
func near(_ a: Double?, _ b: Double) -> Bool { a.map { abs($0 - b) < 1e-9 } ?? false }
check(near(Calculator.evaluate("2+2"), 4), "2+2")
check(near(Calculator.evaluate("2 * (3 + 4)"), 14), "parens")
check(near(Calculator.evaluate("2^10"), 1024), "pow")
check(near(Calculator.evaluate("10 / 4"), 2.5), "div")
check(near(Calculator.evaluate("50 * 20%"), 10), "percent")
check(near(Calculator.evaluate("17 % 5"), 2), "mod")
check(near(Calculator.evaluate("sqrt(16) + 1"), 5), "sqrt")
check(near(Calculator.evaluate("1,200 × 3"), 3600), "times + grouping")
check(Calculator.evaluate("2024") == nil, "plain number isn't maths")
check(Calculator.evaluate("safari") == nil, "word isn't maths")
check(Calculator.evaluate("1/0") == nil, "div by zero")
check(Calculator.evaluate("-5") == nil, "lone negative")
check(Currency.parse("$5") == .init(amount: 5, from: "USD", to: nil), "$5")
check(Currency.parse("5 usd") == .init(amount: 5, from: "USD", to: nil), "5 usd")
check(Currency.parse("€20 in inr") == .init(amount: 20, from: "EUR", to: "INR"), "€20 in inr")
check(Currency.parse("10k yen to gbp") == .init(amount: 10000, from: "JPY", to: "GBP"), "10k yen")
check(Currency.parse("1,250.50 gbp") == .init(amount: 1250.5, from: "GBP", to: nil), "grouped")
check(Currency.parse("page 5") == nil, "page 5")
check(Currency.parse("5 cats") == nil, "5 cats")
check(Currency.parse("5") == nil, "bare number")
check(Currency.parse("₹500 to usd") == .init(amount: 500, from: "INR", to: "USD"), "rupee symbol")
func words(_ q: String) -> Double? { NumberWords.expression(q).flatMap(Calculator.evaluate) }
check(near(words("what is ten times 12"), 120), "ten times 12")
check(near(words("what's 15 percent of 80?"), 12), "15 percent of 80")
check(near(words("twenty five plus seventeen"), 42), "twenty five plus seventeen")
check(near(words("half of 37"), 18.5), "half of 37")
check(near(words("three thousand two hundred divided by 4"), 800), "3200/4")
check(near(words("9 squared"), 81), "squared")
check(near(words("square root of 144"), 12), "sqrt")
check(words("best pasta recipe") == nil, "words: not maths")
check(words("ten") == nil, "words: a lone number")
check(Units.parse("5 km in miles").map { abs($0.value - 3.10686) < 0.001 } == true, "km to miles")
check(Units.parse("72 f to c").map { abs($0.value - 22.2222) < 0.001 } == true, "f to c")
check(Units.parse("3 cups to ml") != nil, "cups to ml")
check(Units.parse("5 km to kg") == nil, "mismatched units")

// Calculator: more shapes
check(near(Calculator.evaluate("(1+2)*(3+4)"), 21), "nested parens")
check(near(Calculator.evaluate("2+3*4"), 14), "precedence")
check(near(Calculator.evaluate("100-25%"), 75) || near(Calculator.evaluate("100-25%"), 99.75), "percent off")
check(near(Calculator.evaluate("3.5*2"), 7), "decimals")
check(near(Calculator.evaluate("10 ÷ 4"), 2.5), "÷ sign")
check(Calculator.evaluate("2+") == nil, "unfinished sum")
check(Calculator.evaluate("(2+3") == nil || near(Calculator.evaluate("(2+3"), 5), "unclosed paren doesn't crash")
check(Calculator.evaluate("") == nil, "empty")
check(Calculator.format(1024) == "1,024", "format groups thousands")
check(Calculator.format(2.5) == "2.5", "format keeps decimals")
check(Calculator.format(4) == "4", "format drops .0")

