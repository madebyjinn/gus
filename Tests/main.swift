// Reminders: the sentence that started this, and its cousins
let cal = Calendar.current
let noon = cal.date(bySettingHour: 12, minute: 0, second: 0, of: Date())!
func draft(_ t: String, now: Date = Date()) -> ReminderParser.Draft? { ReminderParser.draft(t, now: now) }
func clock(_ d: Date?) -> String { d.map { let c = cal.dateComponents([.hour, .minute], from: $0); return "\(c.hour!):\(c.minute!)" } ?? "none" }
let naim = draft("remind me to call naim tonight at 9.30")
check(naim?.title == "Call naim", "naim: title is “Call naim”, got \(naim?.title ?? "nil")")
check(clock(naim?.due) == "21:30", "naim: 9.30 tonight is 21:30, got \(clock(naim?.due))")
check(naim?.due.map { cal.isDateInToday($0) } == true, "naim: tonight is today")
check(clock(draft("remind me to call naim tonight at 9:30")?.due) == "21:30", "colon time")
let mum = draft("remind me to call mum tomorrow at 5")
check(mum?.title == "Call mum" && mum?.due.map { cal.isDateInTomorrow($0) } == true && clock(mum?.due) == "17:0", "tomorrow at 5 is 5 pm tomorrow")
check(draft("remind me to buy milk") == .init(title: "Buy milk", due: nil), "no time: no date")
check(draft("remind me") == nil, "remind me: nothing yet")
check(draft("remind me to") == nil, "remind me to: nothing yet")
check(draft("remind ") == nil, "remind: nothing yet")
check(draft("buy milk") == nil, "no trigger word: not a reminder")
check(draft("reminder pay rent on friday")?.title == "Pay rent", "reminder …: title")
check(draft("todo water the plants")?.title == "Water the plants", "todo …")
let soon = draft("remind me to stretch in 20 minutes", now: noon)
check(soon?.title == "Stretch" && soon?.due == noon.addingTimeInterval(1200), "in 20 minutes")
check(draft("remind me to check the oven in 2 hours", now: noon)?.due == noon.addingTimeInterval(7200), "in 2 hours")
check(draft("remind me to rest in an hour", now: noon)?.due == noon.addingTimeInterval(3600), "in an hour")
check(draft("remind me to renew passport in 3 days", now: noon)?.due == noon.addingTimeInterval(3 * 86400), "in 3 days")
let nine = draft("remind me to call naim at 9", now: noon)
check(nine?.title == "Call naim" && clock(nine?.due) == "21:0" && nine?.due.map { $0 > noon } == true, "at 9, asked at noon, is 9 pm today")
let seven = draft("remind me to run at 7", now: cal.date(bySettingHour: 22, minute: 0, second: 0, of: Date())!)
check(clock(seven?.due) == "7:0", "at 7, asked at 10 pm, is 7 am tomorrow")
check(draft("remind me to call bob at 5.15pm tomorrow")?.title == "Call bob", "time and day in either order")
check(draft("Remind me to Email Sarah")?.title == "Email Sarah", "capitals are kept")
check(ReminderWhen.text(Date()).hasPrefix("Today"), "when: today")
check(ReminderWhen.text(Date().addingTimeInterval(86400)).hasPrefix("Tomorrow"), "when: tomorrow")
check(!ReminderWhen.text(Date().addingTimeInterval(5 * 86400)).hasPrefix("To"), "when: a later day shows its date")
// Typing resets the pick to the first row; a row you picked yourself survives late results.
check(Selection.pick(after: ["a", "b", "c"], keeping: "c", picked: false, answerOnTop: false) == 0, "pick: typing resets to the first row")
check(Selection.pick(after: ["a", "b", "c"], keeping: "c", picked: true, answerOnTop: false) == 2, "pick: your row stays as results land")
check(Selection.pick(after: ["x", "a", "c"], keeping: "c", picked: true, answerOnTop: false) == 2, "pick: your row is followed when it moves")
check(Selection.pick(after: ["a", "b"], keeping: "c", picked: true, answerOnTop: false) == 0, "pick: your row gone, back to the first")
check(Selection.pick(after: ["ans", "a", "c"], keeping: "c", picked: true, answerOnTop: true) == 0, "pick: an answer on top wins")
check(Selection.pick(after: [], keeping: nil, picked: false, answerOnTop: false) == 0, "pick: empty list")
print(fails == 0 ? "all tests passed" : "\(fails) failed")
exit(fails == 0 ? 0 : 1)
